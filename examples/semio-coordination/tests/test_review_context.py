"""Offline generated-context preservation checks; no model calls."""
import copy
import hashlib
import importlib.util
from pathlib import Path
import unittest

PATH = Path(__file__).resolve().parents[1] / "review_context.py"
SPEC = importlib.util.spec_from_file_location("review_context", PATH)
module = importlib.util.module_from_spec(SPEC)
if PATH.exists():
    SPEC.loader.exec_module(module)


class ReviewContextTests(unittest.TestCase):
    def setUp(self):
        self.text = "// Code generated by protoc-gen-go. DO NOT EDIT.\n" + "field\n" * 2000
        self.snapshot = {
            "patch": "FULL DIFF including generated descriptor changes",
            "files": ["rpc/flipt.pb.go", "server/evaluator.go"],
            "sources": {"rpc/flipt.pb.go": self.text, "server/evaluator.go": "whole function"},
            "checks": {"passed": False}, "unresolved_findings": ["compatibility"],
        }
        self.original = copy.deepcopy(self.snapshot)
        self.evidence = {}

    def store(self, text):
        key = hashlib.sha256(text.encode()).hexdigest()
        self.evidence[key] = text
        return key

    def compact(self, **kwargs):
        options = dict(generated_paths=["rpc/flipt.pb.go"], store_text=self.store,
                       read_text=self.evidence.__getitem__, retrieval_available=True)
        options.update(kwargs)
        return module.compact_generated_context(self.snapshot, **options)

    def test_exact_roundtrip_and_all_other_evidence_unchanged(self):
        packed, receipt = self.compact()
        ref = packed.pop("generated_context_refs")["rpc/flipt.pb.go"]
        self.assertEqual(ref["sha256"], hashlib.sha256(self.text.encode()).hexdigest())
        self.assertIn("possibly truncated", ref["notice"])
        self.assertIn("not a full-file hash", ref["notice"])
        self.assertEqual(ref["tool"], "read_evidence")
        packed["sources"]["rpc/flipt.pb.go"] = self.evidence[ref["sha256"]]
        self.assertEqual(packed, self.original)
        self.assertEqual(self.snapshot, self.original)
        self.assertLess(receipt["after_bytes"], receipt["before_bytes"])

    def test_reader_required_even_if_store_exists(self):
        with self.assertRaisesRegex(ValueError, "retrieval"):
            self.compact(retrieval_available=False)
        self.assertFalse(self.evidence)

    def test_explicit_selection_only(self):
        packed, receipt = self.compact(generated_paths=[])
        self.assertEqual(packed, self.original)
        self.assertEqual(receipt["before_bytes"], receipt["after_bytes"])
        self.assertFalse(self.evidence)

    def test_not_generated_or_missing_rejected(self):
        for path in ("server/evaluator.go", "missing.go"):
            with self.subTest(path=path), self.assertRaises(ValueError):
                self.compact(generated_paths=[path])
        self.assertFalse(self.evidence)

    def test_typescript_generated_header_from_kvc(self):
        header = "// GENERATED \u2014 edit docs/kvc/kb and rerun scripts/generate_kvc_help_content.py\n// Do not edit by hand.\n"
        self.snapshot["sources"]["rpc/flipt.pb.go"] = header + "export const help = [];\n" * 100
        packed, _ = self.compact()
        self.assertIn("generated_context_refs", packed)

    def test_incomplete_typescript_header_is_not_sufficient(self):
        for header in ("// GENERATED from source\n", "// Do not edit by hand.\n"):
            self.snapshot["sources"]["rpc/flipt.pb.go"] = header + "content\n" * 100
            with self.subTest(header=header), self.assertRaises(ValueError):
                self.compact()

    def test_tampered_readback_rejected(self):
        with self.assertRaisesRegex(ValueError, "readback"):
            self.compact(read_text=lambda key: "tampered")
        self.assertEqual(self.snapshot, self.original)

    def test_wrong_hash_rejected(self):
        with self.assertRaisesRegex(ValueError, "hash"):
            self.compact(store_text=lambda text: "wrong")

    def test_unavailable_role_scoped_evidence_rejected(self):
        with self.assertRaises(KeyError):
            self.compact(read_text={}.__getitem__)

    def test_storage_failure_leaves_input_untouched(self):
        def fail(text):
            raise OSError("disk full")
        with self.assertRaises(OSError):
            self.compact(store_text=fail)
        self.assertEqual(self.snapshot, self.original)

    def test_existing_references_not_overwritten(self):
        self.snapshot["generated_context_refs"] = {"existing": {}}
        with self.assertRaises(ValueError):
            self.compact()

    def test_small_excerpts_stay_inline(self):
        self.snapshot["sources"]["rpc/flipt.pb.go"] = self.text[:100]
        packed, receipt = self.compact()
        self.assertEqual(packed, self.snapshot)
        self.assertFalse(self.evidence)

    def test_reference_overhead_must_not_expand_snapshot(self):
        marker = "// Code generated by protoc-gen-go. DO NOT EDIT.\n"
        self.snapshot = {"patch": "diff", "sources": {
            "rpc/flipt.pb.go": marker + "x" * (691 - len(marker))}}
        packed, receipt = self.compact()
        self.assertLessEqual(receipt["after_bytes"], receipt["before_bytes"])
        self.assertEqual(packed, self.snapshot)

    def test_utf8_byte_and_character_counts_are_distinct(self):
        self.snapshot["sources"]["rpc/flipt.pb.go"] += "\u00e9"
        packed, _ = self.compact()
        ref = packed["generated_context_refs"]["rpc/flipt.pb.go"]
        self.assertEqual(ref["source_bytes"], ref["total_characters"] + 1)


if __name__ == "__main__":
    unittest.main()
