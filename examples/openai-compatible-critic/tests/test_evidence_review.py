"""Offline bounded retrieval tests. No provider credentials or network."""
import importlib.util
import json
from pathlib import Path
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
import critic

SPEC = importlib.util.spec_from_file_location('evidence_review', ROOT / 'evidence_review.py')
review = importlib.util.module_from_spec(SPEC)
if (ROOT / 'evidence_review.py').exists():
    SPEC.loader.exec_module(review)


class EvidenceReviewTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.out = Path(self.temp.name)
        self.packet = {'artifact_diff': 'full generated descriptor diff', 'result_revision': 'exact',
                       'sources': {'gen.go': '// Code generated by test. DO NOT EDIT.\n' + 'x' * 2000},
                       'checks': ['passed'], 'unresolved_findings': []}
        self.calls = []

    def execute(self, responder, **kwargs):
        paths = kwargs.pop('selected_paths', ['gen.go'])
        def call(**options):
            self.calls.append(options)
            options['on_request']({'messages': options['messages']})
            return {}, responder(options, len(self.calls))
        return review.run_review(self.packet, {}, paths, call=call,
                                 write=critic.write_json, out_dir=self.out,
                                 prompt='Review passive evidence', timeout=10,
                                 provider_options={}, error=critic.HarnessError, **kwargs)

    def final(self):
        return {'usage': {'prompt_tokens': 20, 'completion_tokens': 2},
                'choices': [{'finish_reason': 'stop', 'message': {'content': '{}'}}]}

    def tool(self, options, number, *, key=None, count=200):
        packet = json.loads(options['messages'][1]['content'])['review_packet']
        ref = packet['generated_context_refs']['gen.go']
        return {'usage': {'prompt_tokens': 10, 'completion_tokens': 3}, 'choices': [{
            'finish_reason': 'tool_calls', 'message': {'role': 'assistant', 'content': None,
            'tool_calls': [{'id': f'call-{number}', 'type': 'function', 'function': {
                'name': 'read_evidence', 'arguments': json.dumps({
                    'sha256': key or ref['sha256'], 'offset': 0, 'count': count})}}]}}]}

    def effort(self):
        return json.loads((self.out / 'effort.json').read_text())

    def test_read_then_final_preserves_diff_and_counts_all_calls(self):
        self.execute(lambda o, n: self.tool(o, n) if n == 1 else self.final())
        self.assertEqual(len(self.calls), 2)
        self.assertEqual(self.effort()['extra_read_bytes'], 200)
        self.assertEqual(len(self.effort()['calls']), 2)
        self.assertEqual(self.effort()['calls'][0]['usage']['prompt_tokens'], 10)
        self.assertEqual(self.calls[1]['messages'][-1]['role'], 'tool')
        packet = json.loads(self.calls[0]['messages'][1]['content'])['review_packet']
        self.assertEqual(packet['artifact_diff'], self.packet['artifact_diff'])

    def test_unknown_hash_stops_without_second_call(self):
        with self.assertRaises(critic.HarnessError):
            self.execute(lambda o, n: self.tool(o, n, key='a' * 64))
        self.assertEqual(len(self.calls), 1)
        self.assertEqual(self.effort()['status'], 'incomplete')

    def test_call_budget_stops_tool_loop(self):
        with self.assertRaises(critic.HarnessError):
            self.execute(lambda o, n: self.tool(o, n))
        self.assertEqual(len(self.calls), 3)
        self.assertEqual(len(self.effort()['calls']), 3)
        self.assertIsNone(self.calls[-1]['tools'])

    def test_inline_sources_are_not_offered_for_duplicate_reads(self):
        self.execute(lambda o, n: self.final(), selected_paths=[])
        self.assertIsNone(self.calls[0]['tools'])
        self.assertEqual(self.effort()['extra_read_bytes'], 0)

    def test_invalid_slice_is_not_returned(self):
        with self.assertRaises(critic.HarnessError):
            self.execute(lambda o, n: self.tool(o, n, count=8193))
        self.assertEqual(self.effort()['extra_read_bytes'], 0)

    def test_failed_call_retained_with_unknown_usage(self):
        def fail(o, n):
            raise critic.HarnessError('provider HTTP 503')
        with self.assertRaises(critic.HarnessError):
            self.execute(fail)
        self.assertIsNone(self.effort()['calls'][0]['usage'])
        self.assertEqual(self.effort()['status'], 'incomplete')

    def test_truncated_final_is_incomplete(self):
        final = self.final()
        final['choices'][0]['finish_reason'] = 'length'
        with self.assertRaises(critic.HarnessError):
            self.execute(lambda o, n: final)
        self.assertEqual(self.effort()['status'], 'incomplete')

    def test_no_model_chosen_path_or_execution_tool(self):
        def malicious(o, n):
            p = self.tool(o, n)
            p['choices'][0]['message']['tool_calls'][0]['function']['name'] = 'read_file'
            return p
        with self.assertRaises(critic.HarnessError):
            self.execute(malicious)
        self.assertEqual(self.effort()['extra_read_bytes'], 0)

    def test_actual_runner_exposes_opt_in(self):
        self.assertIn('--evidence-reads', (ROOT / 'critic.py').read_text())


if __name__ == '__main__':
    unittest.main()
